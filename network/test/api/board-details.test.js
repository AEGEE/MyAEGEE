const { startServer, stopServer } = require('../../lib/server');
const { request } = require('../scripts/helpers');
const mock = require('../scripts/mock');
const generator = require('../scripts/generator');

describe('Board details', () => {
    beforeAll(async () => {
        await startServer();
    });

    afterAll(async () => {
        await stopServer();
    });

    beforeEach(async () => {
        mock.mockAll();
    });

    afterEach(async () => {
        await generator.clearAll();
        mock.cleanAll();
    });

    test('should fail if no permission', async () => {
        mock.mockAll({ mainPermissions: { noPermissions: true } });

        const board = await generator.createBoard();

        const res = await request({
            path: '/bodies/' + board.body_id + '/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(403);
        expect(res.body.success).toEqual(false);
    });

    test('should succeed if everything is okay', async () => {
        const board = await generator.createBoard();

        const res = await request({
            path: '/bodies/' + board.body_id + '/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(200);
        expect(res.body.success).toEqual(true);
        expect(res.body).not.toHaveProperty('errors');
        expect(res.body).toHaveProperty('data');
        expect(res.body.data.id).toEqual(board.id);
    });

    test('should fail if board is not found', async () => {
        const res = await request({
            path: '/bodies/1/boards/1337',
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(404);
        expect(res.body.success).toEqual(false);
        expect(res.body).not.toHaveProperty('data');
        expect(res.body).toHaveProperty('message');
    });

    test('should fail if board id is not a number', async () => {
        const res = await request({
            path: '/bodies/1/boards/NaN',
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(400);
        expect(res.body.success).toEqual(false);
        expect(res.body).not.toHaveProperty('data');
        expect(res.body).toHaveProperty('message');
    });

    test('should fail if board id is not an integer', async () => {
        const res = await request({
            path: '/bodies/1/boards/1.5',
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(400);
        expect(res.body.success).toEqual(false);
        expect(res.body).not.toHaveProperty('data');
        expect(res.body).toHaveProperty('message');
    });

    test('should fail if board id is above the maximum ID', async () => {
        const res = await request({
            path: '/bodies/1/boards/2147483648',
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(400);
        expect(res.body.success).toEqual(false);
        expect(res.body).not.toHaveProperty('data');
        expect(res.body).toHaveProperty('message');
    });

    test('should fail if body_id is not a number', async () => {
        const board = await generator.createBoard();

        const res = await request({
            path: '/bodies/lalala/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(400);
        expect(res.body.success).toEqual(false);
        expect(res.body.message).toEqual('Body ID is invalid.');
    });

    test('should fail if the board belongs to another body', async () => {
        const board = await generator.createBoard({ body_id: 1 });

        const res = await request({
            path: '/bodies/2/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(404);
        expect(res.body.success).toEqual(false);
    });

    test('should show a board to members holding only the global view permission', async () => {
        mock.mockAll({ mainPermissions: { viewOnly: true }, managePermissions: { noPermissions: true } });

        const board = await generator.createBoard({ body_id: 34 });

        const res = await request({
            path: '/bodies/34/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(200);
        expect(res.body.data.id).toEqual(board.id);
    });

    test('should not show a board to a board manager of the body without the view permission', async () => {
        // The user manages body 34 locally, but holds no global permission.
        mock.mockAll({ mainPermissions: { noPermissions: true } });

        const board = await generator.createBoard({ body_id: 34 });

        const res = await request({
            path: '/bodies/34/boards/' + board.id,
            method: 'GET',
            headers: { 'X-Auth-Token': 'blablabla' }
        });

        expect(res.statusCode).toEqual(403);
        expect(res.body.success).toEqual(false);
    });
});
